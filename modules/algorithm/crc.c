#define CRC_CONTEXT_INITIALIZED 0x43524331u

// 先核对编号再访问配置，避免错误编号成为数组下标。
static CRCStatus_t CRCValidate(const CRCContext_t *context)
{
    if (context == NULL) return CRC_ERROR_ARGUMENT;
    if (context->initialized != CRC_CONTEXT_INITIALIZED) return CRC_ERROR_STATE;
    if ((unsigned)context->algorithm >= CRC_ALGORITHM_COUNT) return CRC_ERROR_ALGORITHM;
    uint8_t width = CRCConfigurations[context->algorithm].width;
    if (width < 32u && (context->remainder >> width) != 0u) return CRC_ERROR_STATE;
    return CRC_OK;
}

CRCStatus_t CRCInit(CRCContext_t *context, CRCAlgorithm_t algorithm)
{
    if (context == NULL) return CRC_ERROR_ARGUMENT;
    if ((unsigned)algorithm >= CRC_ALGORITHM_COUNT) return CRC_ERROR_ALGORITHM;
    CRCContext_t next = {algorithm, CRCConfigurations[algorithm].initial, CRC_CONTEXT_INITIALIZED};
    *context = next;
    return CRC_OK;
}

CRCStatus_t CRCUpdate(CRCContext_t *context, const uint8_t *data, size_t length)
{
    CRCStatus_t status = CRCValidate(context);
    if (status != CRC_OK) return status;
    if (data == NULL && length != 0u) return CRC_ERROR_ARGUMENT;
    uint32_t value = context->remainder;
    // 数据长度由调用方实际缓冲区决定，每次只处理一个字节，无首次调用写表。
    for (size_t index = 0u; index < length; ++index)
    {
        uint8_t byte = data[index];
        switch (context->algorithm)
        {
        case CRC8_CAN_A5: value = crc_table_0[(value ^ byte) & 0xffu]; break;
        case CRC8_REFEREE: value = crc_table_1[(value ^ byte) & 0xffu]; break;
        case CRC16_MODBUS_A5: value = (value >> 8u) ^ crc_table_2[(value ^ byte) & 0xffu]; break;
        case CRC16_SP_REFEREE: value = (value >> 8u) ^ crc_table_3[(value ^ byte) & 0xffu]; break;
        case CRC32_IEEE: value = (value >> 8u) ^ crc_table_4[(value ^ byte) & 0xffu]; break;
        default: return CRC_ERROR_ALGORITHM;
        }
    }
    // 入口检查通过后才更新调用者保存的历史数据。
    context->remainder = value;
    return CRC_OK;
}

CRCStatus_t CRCFinal(const CRCContext_t *context, uint32_t *output)
{
    CRCStatus_t status = CRCValidate(context);
    if (status != CRC_OK) return status;
    if (output == NULL) return CRC_ERROR_ARGUMENT;
    *output = context->remainder ^ CRCConfigurations[context->algorithm].xor_output;
    return CRC_OK;
}

CRCStatus_t CRCCompute(CRCAlgorithm_t algorithm, const uint8_t *data,
                       size_t length, uint32_t *output)
{
    if (output == NULL || (data == NULL && length != 0u)) return CRC_ERROR_ARGUMENT;
    CRCContext_t context = {0};
    CRCStatus_t status = CRCInit(&context, algorithm);
    if (status == CRC_OK) status = CRCUpdate(&context, data, length);
    if (status == CRC_OK) status = CRCFinal(&context, output);
    return status;
}
