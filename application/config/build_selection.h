/** @file build_selection.h
 * @brief 正式固件读取CMake生成的选择；独立主机回归保留原有组合。
 */
#ifndef MC02_BUILD_SELECTION_H
#define MC02_BUILD_SELECTION_H
#if defined(MC02_CONFIG_GENERATED)
#include "mc02_build_config.h"
#else
#define MC02_FEATURE_SAFETY 1
#define MC02_FEATURE_IMU 1
#define MC02_FEATURE_COMMUNICATION 1
#define MC02_FEATURE_COMMAND 1
#define MC02_FEATURE_CHASSIS 1
#define MC02_FEATURE_GIMBAL 1
#define MC02_FEATURE_SHOOTER 1
#define MC02_FEATURE_REFEREE 1
#define MC02_FEATURE_VISION 1
#define MC02_FEATURE_REMOTE 1
#define MC02_FEATURE_ALARM 1
#define MC02_FEATURE_LCD 1
#define MC02_FEATURE_UI 1
#define MC02_FEATURE_SUPERCAP 1
#define MC02_FEATURE_LOG 1
#define MC02_FEATURE_HEATER 1
#define MC02_FEATURE_ADC 1
#define MC02_FEATURE_MOTOR_CONTROL 1
#define MC02_FEATURE_COMM_DISPATCH 1
#define MC02_SELECTED_DRIVER_DJI 1
#define MC02_SELECTED_DRIVER_LK 1
#define MC02_SELECTED_DRIVER_HT 1
#define MC02_SELECTED_DRIVER_DM 0
#define MC02_CHASSIS_IS_OMNI 0
#endif

// 已登记的固件配置在启动时检查常驻任务的固定拍点，并在运行中使用同一规则。
#if defined(MC02_PROFILE_BENCH_SAFE) || defined(MC02_PROFILE_COMMISSIONING) || defined(MC02_PROFILE_ROBOT)
#define MC02_TASK_FIXED_REGULAR_PERIODS 1
#else
#define MC02_TASK_FIXED_REGULAR_PERIODS 0
#endif

// 有底盘运动任务的生成配置使用独立拍点；观察版与旧组合不启用。
#if defined(MC02_CONFIG_GENERATED) && (defined(MC02_PROFILE_ROBOT) || defined(MC02_PROFILE_COMMISSIONING_CHASSIS)) && MC02_FEATURE_CHASSIS
#define MC02_TASK_CHASSIS 1
#else
#define MC02_TASK_CHASSIS 0
#endif

// 正式生成配置中，各已启用的机构由独立任务调用。
#if defined(MC02_CONFIG_GENERATED) && defined(MC02_PROFILE_ROBOT) && MC02_FEATURE_GIMBAL
#define MC02_TASK_GIMBAL 1
#else
#define MC02_TASK_GIMBAL 0
#endif
#if defined(MC02_CONFIG_GENERATED) && defined(MC02_PROFILE_ROBOT) && MC02_FEATURE_SHOOTER
#define MC02_TASK_SHOOTER 1
#else
#define MC02_TASK_SHOOTER 0
#endif
#define MC02_TASK_CONTROL (MC02_TASK_CHASSIS || MC02_TASK_GIMBAL || MC02_TASK_SHOOTER)

// DJI 底盘调试与正式控制使用分开的计算与发送拍点。
#if defined(MC02_CONFIG_GENERATED) && (defined(MC02_PROFILE_ROBOT) || defined(MC02_PROFILE_COMMISSIONING_CHASSIS)) && MC02_FEATURE_MOTOR_CONTROL && \
    MC02_SELECTED_DRIVER_DJI && !MC02_SELECTED_DRIVER_LK && !MC02_SELECTED_DRIVER_HT && !MC02_SELECTED_DRIVER_DM
#define MC02_TASK_MOTOR_SPLIT 1
#else
#define MC02_TASK_MOTOR_SPLIT 0
#endif
#endif
