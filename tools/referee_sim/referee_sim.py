def crc8(data, crc=0xFF):
    for b in data:
        crc = CRC8_TAB[(crc ^ b) & 0xFF]
    return crc


def crc16(data, crc=0xFFFF):
    for b in data:
        crc ^= b
        for _ in range(8):
            if crc & 1:
                crc = ((crc >> 1) ^ 0x8408) & 0xFFFF
            else:
                crc = (crc >> 1) & 0xFFFF
    return crc


def frame(cmd_id, data, seq=0):
    header = bytes([0xA5]) + struct.pack('<H', len(data)) + bytes([seq & 0xFF])
    header += bytes([crc8(header)])
    body = header + struct.pack('<H', cmd_id) + data
    return body + struct.pack('<H', crc16(body))


def game_state_frame(seq):
    # 0x0001: game_type(4bit) + game_progress(4bit), stage_remain_time(u16), SyncTimeStamp(u64)
    data = bytes([0x40]) + struct.pack('<H', 300) + struct.pack('<Q', 0)
    return frame(0x0001, data, seq)


def robot_state_frame(seq):
    # 0x0201: robot_id, robot_level, current_HP, maximum_HP, cooling, heat_limit, power_limit, 输出使能位
    data = struct.pack('<BBHHHHHB', 7, 1, 100, 100, 0, 240, 45, 0x07)
    return frame(0x0201, data, seq)


def power_heat_frame(seq):
    # 0x0202: chassis_voltage, chassis_current, chassis_power(float), buffer_energy, 3x heat
    data = struct.pack('<HHfHHHH', 240, 100, 45.0, 60, 0, 0, 0)
    return frame(0x0202, data, seq)


def shoot_frame(seq):
    # 0x0207: bullet_type, shooter_id, bullet_freq, bullet_speed(float)
    data = bytes([1, 1, 10]) + struct.pack('<f', 30.0)
    return frame(0x0207, data, seq)


def build_large_length_frame():
    # 声明 data_length=0xFFFF, 实际只发 9 字节(合法CRC), 用于触发长度边界保护
    header = bytes([0xA5]) + struct.pack('<H', 0xFFFF) + bytes([0])
    header += bytes([crc8(header)])
    body = header + struct.pack('<H', 0x0001)
    return body + struct.pack('<H', crc16(body))


def build_short_data_frame():
    # cmd=0x0001 但 data_length=0, CRC 合法, 用于触发按命令码的数据段长度保护
    return frame(0x0001, b'', 0)


def send(port, data, rounds=1, interval=0.05):
    with serial.Serial(port, BAUD, timeout=1) as ser:
        for _ in range(rounds):
            ser.write(data)
            time.sleep(interval)


def main():
    phase = sys.argv[1] if len(sys.argv) > 1 else 'valid'
    if phase == 'valid':
        for seq in range(50):
            send(PORT, game_state_frame(seq) + robot_state_frame(seq) + power_heat_frame(seq) + shoot_frame(seq))
        print('valid frames sent')
    elif phase == 'large':
        send(PORT, build_large_length_frame(), rounds=20)
        print('large-length frame sent')
    elif phase == 'short':
        send(PORT, build_short_data_frame(), rounds=20)
        print('short-data frame sent')
    elif phase == 'burst':
        send(PORT, bytes([0xA5]) * 200, rounds=20)
        print('0xA5 burst sent')
    elif phase == 'multi':
        send(PORT, robot_state_frame(1) + game_state_frame(2), rounds=20)
        print('multi-frame burst sent')
    else:
        print('unknown phase')


if __name__ == '__main__':
    main()
